// The `apps/web/.env.local` a worktree's `pnpm dev` runs with. Node runs the CLIs that import this
// directly (type stripping), so relative imports keep their `.ts` extension.
import { join } from "node:path";

/** compose.verify.yaml's published ports: never the dev stack's 5432, 6379, 1025 and 8025. */
export const VERIFY_PORTS = { postgres: 5433, redis: 6380, smtp: 1026, mailpit: 8026 } as const;

type WorktreeEnvFileArgs = {
  /** The main checkout's `.secrets/`, absolute: a worktree has none of its own. */
  secretsDir: string;
  database: string;
  redisPrefix: string;
};

export function worktreeEnvFile({ secretsDir, database, redisPrefix }: WorktreeEnvFileArgs) {
  const secret = (name: string) => join(secretsDir, name);
  return `# Generated by pnpm dev:env for this worktree, and rewritten by every \`pnpm dev\` here: edits are lost.
# It points at the worktree's own database and Redis prefix on the verification services
# (compose.verify.yaml), never the main checkout's dev stack. \`pnpm dev:teardown\` removes them.

DATABASE_URL=postgres://app@localhost:${VERIFY_PORTS.postgres}/${database}
DATABASE_PASSWORD_FILE=${secret("db_app_password")}

REDIS_URL=redis://app@localhost:${VERIFY_PORTS.redis}
REDIS_PASSWORD_FILE=${secret("redis_password")}
REDIS_KEY_PREFIX=${redisPrefix}

# Shared by every worktree: the sign-in harness picks out each email by recipient and time.
EMAIL_TRANSPORT=smtp
SMTP_URL=smtp://localhost:${VERIFY_PORTS.smtp}
MAILPIT_URL=http://127.0.0.1:${VERIFY_PORTS.mailpit}

BETTER_AUTH_SECRET_FILE=${secret("better_auth_secret")}
AUTH_TRUSTED_IP_HEADER=x-forwarded-for
`;
}
