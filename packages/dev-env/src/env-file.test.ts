import { parseEnv } from "node:util";
import { worktreeEnvFile } from "./env-file.ts";

const file = worktreeEnvFile({
  secretsDir: "/repo/.secrets",
  database: "wt_task_0ebb429f",
  redisPrefix: "cw:wt:task_0ebb429f:",
});
const vars = parseEnv(file);

describe("worktreeEnvFile", () => {
  it("points the app at the worktree's own database on the verification Postgres, as `app`", () => {
    expect(vars.DATABASE_URL).toBe("postgres://app@localhost:5433/wt_task_0ebb429f");
    expect(vars.DATABASE_PASSWORD_FILE).toBe("/repo/.secrets/db_app_password");
  });

  it("points the app at the verification Redis under the worktree's prefix", () => {
    expect(vars.REDIS_URL).toBe("redis://app@localhost:6380");
    expect(vars.REDIS_PASSWORD_FILE).toBe("/repo/.secrets/redis_password");
    expect(vars.REDIS_KEY_PREFIX).toBe("cw:wt:task_0ebb429f:");
  });

  it("sends mail to the shared verification Mailpit, which the sign-in harness reads", () => {
    expect(vars.EMAIL_TRANSPORT).toBe("smtp");
    expect(vars.SMTP_URL).toBe("smtp://localhost:1026");
    expect(vars.MAILPIT_URL).toBe("http://127.0.0.1:8026");
  });

  it("reads the auth secret from the main checkout's .secrets by absolute path", () => {
    expect(vars.BETTER_AUTH_SECRET_FILE).toBe("/repo/.secrets/better_auth_secret");
  });

  it("trusts the header portless appends the client address to", () => {
    expect(vars.AUTH_TRUSTED_IP_HEADER).toBe("x-forwarded-for");
  });

  it("never names the dev stack's ports", () => {
    expect(file).not.toMatch(/:(5432|6379|1025|8025)\b/);
  });

  it("says it's generated, so nobody edits it by hand", () => {
    expect(file.split("\n")[0]).toMatch(/^# Generated by pnpm dev:env/);
  });
});
