// Friction reports on GitHub (docs/agents/friction.md): filing one, triaging one with a decision
// from `triage.ts`, and gathering a batch for `fix.ts`. `cw friction …` (`@repo/cli`) runs these;
// the rules and their tests live here.
import type { Comment, GitHub, Issue, IssueSummary } from "./github.ts";
import type { Brief, Triage, TriageDecision, TriagePromptArgs } from "./triage.ts";

export const FRICTION = "friction";
/** A report with one of these has been triaged, or set aside by a human. */
export const TRIAGED = ["ready-for-agent", "ready-for-human", "wontfix"] as const;

const TRIAGE_HEADER = "> *This was generated by AI during triage.*\n\n";
const TRIAGE_FOOTER = "\n\n---\n_Triaged by `pnpm cw friction triage` (Haiku)._";

/** How `gh` names the author of a comment the repo's workflows post (`GITHUB_TOKEN`). */
const WORKFLOW_AUTHOR = "github-actions";
const BRIEF_HEADING = "## Agent Brief";

/** Comments from people with write access: anyone can comment on a public issue. */
export function trustedComments(comments: Comment[]): { author: string; body: string }[] {
  return comments
    .filter(({ association }) => ["OWNER", "MEMBER", "COLLABORATOR"].includes(association))
    .map(({ author, body }) => ({ author, body }));
}

/**
 * The brief from triage's latest comment, or null. Only that block, from a workflow comment in
 * triage's own layout: the fixer gets it as Haiku's reading of the report, never other bot
 * comments, which quote report text (a duplicate's title) or the fixer's own notes.
 */
export function triageBrief(comments: Comment[]): string | null {
  const latest = comments.findLast(
    ({ author, body }) =>
      author === WORKFLOW_AUTHOR &&
      /^`ready-for-(agent|human)`: /.test(body.slice(TRIAGE_HEADER.length)) &&
      body.startsWith(TRIAGE_HEADER) &&
      body.endsWith(TRIAGE_FOOTER) &&
      body.includes(`\n\n${BRIEF_HEADING}\n`),
  );
  if (!latest) return null;
  // The last heading: the brief is the comment's final block, and `reason` is one line.
  const start = latest.body.lastIndexOf(`\n\n${BRIEF_HEADING}\n`) + 2;
  return latest.body.slice(start, -TRIAGE_FOOTER.length);
}

const list = (items: string[]) => items.map((item) => `- ${item}`).join("\n") || "- None";

/** The agent brief as a comment, in the triage skill's `AGENT-BRIEF.md` layout. */
export function briefMarkdown(brief: Brief): string {
  return [
    BRIEF_HEADING,
    `**Summary:** ${brief.summary}`,
    `**Current behavior:**\n${brief.current_behavior}`,
    `**Desired behavior:**\n${brief.desired_behavior}`,
    `**Key interfaces:**\n${list(brief.key_interfaces)}`,
    `**Acceptance criteria:**\n${brief.acceptance_criteria.map((item) => `- [ ] ${item}`).join("\n") || "- None"}`,
    `**Out of scope:**\n${list(brief.out_of_scope)}`,
  ].join("\n\n");
}

type ReportBodyArgs = { what: string; cost: string; where: string; fix?: string };

/** The body `docs/agents/friction.md` asks for, from its sections. */
export function reportBody({ what, cost, where, fix }: ReportBodyArgs): string {
  const sections = [
    ["What happened", what],
    ["Cost", cost],
    ["Where", where],
    ["Suggested fix", fix],
  ] as const;
  return sections
    .filter(([, text]) => text?.trim())
    .map(([heading, text]) => `## ${heading}\n${text!.trim()}`)
    .join("\n\n");
}

/** Open (and with `closed`, closed) friction reports matching `search`, newest first. */
export async function searchReports(
  github: GitHub,
  { search, closed }: { search: string; closed: boolean },
): Promise<IssueSummary[]> {
  return await github.list({
    state: closed ? "all" : "open",
    labels: [FRICTION],
    search: search || undefined,
    limit: 20,
  });
}

/** What triage does to GitHub, in order; a dry run returns them without doing them. */
export type Action =
  | { kind: "label"; number: number; add: string[]; remove: string[] }
  | { kind: "comment"; number: number; body: string }
  | { kind: "close"; number: number; comment: string };

export type TriageOutcome =
  | { status: "already_triaged"; labels: string[]; actions: [] }
  | {
      status: "triaged";
      decision: Triage["decision"];
      duplicateOf: number | null;
      reason: string;
      actions: Action[];
    };

type ReportErrorArgs = { code: string; message: string; retryable?: boolean };

/** A refusal with a code an agent branches on (`cw`'s error output), and whether a retry may help. */
export class ReportError extends Error {
  override name = "ReportError";
  readonly code: string;
  readonly retryable: boolean;

  constructor({ code, message, retryable = false }: ReportErrorArgs) {
    super(message);
    this.code = code;
    this.retryable = retryable;
  }
}

/** A gathered report, as triage hands it to the model; the repo's guides are added after. */
export type TriageInput = Omit<TriagePromptArgs, "guide" | "claudeMd">;

type TriageReportArgs = {
  number: number;
  /** The model's call (`triage.ts`), handed the gathered report. */
  decide: (input: TriageInput) => Promise<TriageDecision>;
  /** Triage it again although it carries a triage label; the new label replaces the old. */
  retriage: boolean;
  dryRun: boolean;
};

/** One line, so the model's text can't pass for the brief block (`triageBrief`). */
const oneLine = (text: string) => text.replaceAll(/\s+/g, " ").trim();

/** The labels, comments and close that carry out `answer` for `issue`. */
export function triageActions({
  issue,
  open,
  answer,
}: {
  issue: Issue;
  open: IssueSummary[];
  answer: TriageDecision;
}): Action[] {
  const { number } = issue;
  const reason = oneLine(answer.reason);
  // What the verdict rests on: the files triage read and the searches it ran.
  const checked =
    answer.checked.length > 0 ? `\n\nChecked: ${oneLine(answer.checked.join(", "))}.` : "";
  const stale = (keep?: string) =>
    TRIAGED.filter((label) => label !== keep && issue.labels.includes(label));
  if (answer.decision === "already-fixed") {
    const fixedIn = oneLine(answer.fixed_in ?? "");
    if (!fixedIn) {
      return [
        { kind: "label", number, add: ["ready-for-human"], remove: stale("ready-for-human") },
        {
          kind: "comment",
          number,
          body: `${TRIAGE_HEADER}Triage called this already fixed but named no place it lives: ${reason}${checked}${TRIAGE_FOOTER}`,
        },
      ];
    }
    return [
      { kind: "label", number, add: ["wontfix"], remove: stale("wontfix") },
      {
        kind: "close",
        number,
        comment: `${TRIAGE_HEADER}Already fixed in ${fixedIn}. ${reason}${checked}${TRIAGE_FOOTER}`,
      },
    ];
  }
  if (answer.decision === "duplicate") {
    const original = answer.duplicate_of;
    // Only an open friction report other than this one counts.
    if (original === null || !open.some((report) => report.number === original)) {
      return [
        { kind: "label", number, add: ["ready-for-human"], remove: stale("ready-for-human") },
        {
          kind: "comment",
          number,
          body: `${TRIAGE_HEADER}Triage called this a duplicate but named no open friction report: ${reason}${TRIAGE_FOOTER}`,
        },
      ];
    }
    return [
      {
        kind: "comment",
        number: original,
        body: `${TRIAGE_HEADER}Another occurrence: #${number} (${issue.title}). ${reason}${TRIAGE_FOOTER}`,
      },
      {
        kind: "close",
        number,
        comment: `${TRIAGE_HEADER}Duplicate of #${original}. ${reason}${TRIAGE_FOOTER}`,
      },
    ];
  }
  const brief = answer.brief ? `\n\n${briefMarkdown(answer.brief)}` : "";
  return [
    { kind: "label", number, add: [answer.decision], remove: stale(answer.decision) },
    {
      kind: "comment",
      number,
      body: `${TRIAGE_HEADER}\`${answer.decision}\`: ${reason}${checked}${brief}${TRIAGE_FOOTER}`,
    },
  ];
}

async function apply(github: GitHub, { action }: { action: Action }) {
  if (action.kind === "label") await github.editLabels(action);
  else if (action.kind === "comment") await github.comment(action);
  else await github.close(action);
}

/**
 * Triages friction report `number`: gathers it (with trusted comments only) beside the other open
 * reports and the recently closed ones, asks `decide`, and labels, comments or closes it.
 */
export async function triageReport(
  github: GitHub,
  { number, decide, retriage, dryRun }: TriageReportArgs,
): Promise<TriageOutcome> {
  const issue = await github.view(number);
  if (!issue.labels.includes(FRICTION)) {
    throw new ReportError({
      code: "not_a_friction_report",
      message: `#${number} has no ${FRICTION} label.`,
    });
  }
  if (issue.state !== "open") {
    throw new ReportError({ code: "not_open", message: `#${number} is closed.` });
  }
  const triagedAs = TRIAGED.filter((label) => issue.labels.includes(label));
  if (triagedAs.length > 0 && !retriage) {
    return { status: "already_triaged", labels: triagedAs, actions: [] };
  }
  const [open, closed] = await Promise.all([
    github.list({ state: "open", labels: [FRICTION], limit: 200 }),
    github.list({ state: "closed", labels: [FRICTION], limit: 60 }),
  ]);
  const others = open.filter((report) => report.number !== number);
  const answer = await decide({
    issue: JSON.stringify({
      number,
      title: issue.title,
      body: issue.body,
      labels: issue.labels,
      comments: trustedComments(issue.comments),
    }),
    open: JSON.stringify(
      others.map((other) => ({
        number: other.number,
        title: other.title,
        body: other.body.slice(0, 600),
      })),
    ),
    closed: JSON.stringify(
      closed.map((report) => ({
        number: report.number,
        title: report.title,
        closedAt: report.closedAt,
      })),
    ),
  });
  const actions = triageActions({ issue, open: others, answer });
  if (!dryRun) {
    // oxlint-disable-next-line no-await-in-loop -- in order: the original's comment before the close
    for (const action of actions) await apply(github, { action });
  }
  return {
    status: "triaged",
    decision: answer.decision,
    duplicateOf: answer.decision === "duplicate" ? answer.duplicate_of : null,
    reason: answer.reason,
    actions,
  };
}

type TriageBacklogArgs = Omit<TriageReportArgs, "number" | "retriage"> & {
  /** At most this many reports a run. */
  limit: number;
  /** A report filed more recently is left to the triage run its label started. */
  olderThanMinutes: number;
  now?: Date;
};

/**
 * Triages the open friction reports that carry no triage label and no workflow comment, oldest
 * first: those whose own triage run failed or never started (one filed with a workflow's token
 * starts none). A report it can't triage is recorded in `failed`, and the rest still go.
 */
export async function triageBacklog(
  github: GitHub,
  { decide, limit, olderThanMinutes, now = new Date(), dryRun }: TriageBacklogArgs,
) {
  const cutoff = now.getTime() - olderThanMinutes * 60_000;
  const open = await github.list({ state: "open", labels: [FRICTION], limit: 200 });
  const unlabelled = open
    .filter(({ labels }) => !TRIAGED.some((label) => labels.includes(label)))
    .filter(({ createdAt }) => Date.parse(createdAt) <= cutoff)
    .toSorted((a, b) => Date.parse(a.createdAt) - Date.parse(b.createdAt));
  const triaged: { issue: number; decision: Triage["decision"] }[] = [];
  const failed: { issue: number; code: string; message: string }[] = [];
  for (const { number } of unlabelled) {
    if (triaged.length + failed.length >= limit) break;
    try {
      // A workflow has had its say: a fix in the bot's PR takes the triage label off.
      // oxlint-disable-next-line no-await-in-loop -- one at a time, up to the limit
      const { comments } = await github.view(number);
      if (comments.some(({ author }) => author === WORKFLOW_AUTHOR)) continue;
      // oxlint-disable-next-line no-await-in-loop -- one at a time, so a duplicate sees the last close
      const outcome = await triageReport(github, { number, decide, retriage: false, dryRun });
      if (outcome.status === "triaged") triaged.push({ issue: number, decision: outcome.decision });
    } catch (error) {
      const code =
        error instanceof Error && "code" in error && typeof error.code === "string"
          ? error.code
          : "error";
      failed.push({
        issue: number,
        code,
        message: error instanceof Error ? error.message : String(error),
      });
    }
  }
  return { triaged, failed };
}

/** Reports `numbers`, with trusted comments and triage's brief only, as the fixer's prompt takes them. */
export async function gatherReports(github: GitHub, { numbers }: { numbers: number[] }) {
  const issues = await Promise.all(numbers.map((number) => github.view(number)));
  const missing = issues.filter((issue) => !issue.labels.includes(FRICTION));
  if (missing.length > 0) {
    throw new ReportError({
      code: "not_a_friction_report",
      message: `No ${FRICTION} label on ${missing.map(({ number }) => `#${number}`).join(", ")}.`,
    });
  }
  return issues.map(({ number, title, body, comments }) => ({
    number,
    title,
    body,
    comments: trustedComments(comments),
    triageBrief: triageBrief(comments),
  }));
}
